/**
 * One condition, as a C# `UnlockCond` factory call.
 *
 * GENERATED RATHER THAN TRANSCRIBED, because a lock retyped wrong is either a chassis nobody can
 * earn or one everybody gets for free, and neither announces itself. The `never` cases are emitted
 * as `never` and NOT quietly given a plausible number: `never` means the criteria have not been
 * written, and inventing one here would be making a design decision by accident.
 */
function condOf(c: unknown): string {
  const u = c as Record<string, unknown> | undefined;
  if (u === undefined) return 'UnlockCond.Never()';
  const w = (id: unknown): string => `WeaponIds.${csEnum(String(id))}`;
  const ws = (ids: unknown): string => (ids as string[]).map(w).join(', ');

  switch (u.kind) {
    case 'always': return 'UnlockCond.Always()';
    case 'never': return 'UnlockCond.Never()';
    case 'wave': return `UnlockCond.Wave(${u.wave})`;
    case 'survive': return `UnlockCond.Survive(${u.sec})`;
    case 'kills': return `UnlockCond.Kills(${u.count})`;
    case 'chassisOwned': return `UnlockCond.ChassisOwned(${u.count})`;
    case 'win': return 'UnlockCond.Win()';
    case 'winLevel': return `UnlockCond.WinLevel("${u.level}")`;
    case 'fullRepair': return 'UnlockCond.FullRepair()';
    case 'lasersOverheated': return 'UnlockCond.LasersOverheated()';
    case 'contactHits': return `UnlockCond.ContactHits(${u.count})`;
    case 'diedTo': return `UnlockCond.DiedTo("${u.rank}")`;
    case 'bossKillHolding': return `UnlockCond.BossKillHolding(${w(u.weapon)})`;
    case 'bossKillBy': return `UnlockCond.BossKillBy(${ws(u.weapons)})`;
    case 'killsWith': return `UnlockCond.KillsWith(${u.count}, ${ws(u.weapons)})`;
    case 'killsWithTotal': return `UnlockCond.KillsWithTotal(${u.count}, ${ws(u.weapons)})`;
    case 'splashKillsTotal': return `UnlockCond.SplashKillsTotal(${u.count})`;
    case 'reloadsTotal': return `UnlockCond.ReloadsTotal(${u.count})`;
    case 'tier': {
      const i = UPGRADE_CATALOG.findIndex((d) => d.id === u.id);
      if (i < 0) throw new Error(`tier condition names an unknown card: ${String(u.id)}`);
      return `UnlockCond.Tier(${i}, ${u.tier})`;
    }
    default: throw new Error(`unhandled unlock kind: ${String(u.kind)}`);
  }
}

/** `missile-short` -> `MissileShort`, matching the C# WeaponIds members. */
function csEnum(id: string): string {
  return id.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
}

/*
 * THE ONE LINE UNDER THE NAME comes along too. A chassis's `identity` and a yard's `blurb` are the
 * only thing either pick screen says about what you are choosing - "Sixteen chassis, eight carry a
 * bonus to one weapon" is the whole difference between them - and a port that drew the name alone
 * would be asking a player to pick blind.
 *
 * `playable` is NOT the same fact as the unlock condition and both are carried. A level can be
 * unfinished (nobody may enter), finished but unearned (locked on this save), or open; the pick
 * screen flags the first "TBD" and the second "LOCKED", and collapsing them would tell a player to
 * go and win something that does not exist yet.
 */
const heroRows = HERO_CATALOG.map((h) => {
  const r = h as unknown as Record<string, unknown>;
  return `        new("${cs(String(r.id))}", "${cs(String(r.name))}", ${condOf(r.unlock)}, ` +
    `"${cs(String(r.identity))}", true, "${cs(String(r.sprite))}"),`;
}).join('\n');

const levelRows = LEVEL_CATALOG.map((l) => {
  const r = l as unknown as Record<string, unknown>;
  return `        new("${cs(String(r.id))}", "${cs(String(r.name))}", ${condOf(r.unlock)}, ` +
    `"${cs(String(r.blurb))}", ${r.playable === true}, "${cs(String(r.art))}"),`;
}).join('\n');

const cardLockRows = UPGRADE_CATALOG
  .map((u, i) => [u, i] as const)
  .filter(([u]) => (u as unknown as Record<string, unknown>).unlock !== undefined)
  .map(([u, i]) => {
    const r = u as unknown as Record<string, unknown>;
    return `        new(${i}, "${cs(String(r.id))}", "${cs(String(r.name))}", ${condOf(r.unlock)}),`;
  })
  .join('\n');

/**
 * EVERY upgrade id, in catalog order, and the ones that carry a tier 8.
 *
 * Emitted into `Scrapyard.Meta` because that is where the SAVE lives, and the save's ids have to be
 * filterable against the catalog without reaching into the drawing layer - which `Scrapyard.Meta`
 * cannot see and must not. `CardTexts` carries the same ids in `Scrapyard.Game` for the screens;
 * both come from this one line, so they cannot disagree.
 *
 * The ascension list names PARENT ids and is emitted as a bare list of strings rather than as
 * anything that says how many there are in total, for the reason the whole ascension apparatus is
 * built the way it is: a count is a leak. It is used to drop a stored id whose tier 8 has been
 * withdrawn, and nothing reads it before then.
 */
const allCardIdRows = UPGRADE_CATALOG
  .map((u) => `        "${cs(String((u as unknown as Record<string, unknown>).id))}",`)
  .join('\n');

const ascendedCardIdRows = UPGRADE_CATALOG
  .filter((u) => (u as unknown as Record<string, unknown>).ascension !== undefined)
  .map((u) => `        "${cs(String((u as unknown as Record<string, unknown>).id))}",`)
  .join('\n');

