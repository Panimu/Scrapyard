/**
 * Emits the C# front-end's text and shop tables from the catalogs that own them.
 *
 *   npx tsx tools/gen_ui_text.ts
 *
 * Two files, one command:
 *
 *   cs/src/Scrapyard.Game/CardTexts.cs      upgrade card names and descriptions
 *   cs/src/Scrapyard.Meta/WorkshopText.cs   workshop names, blurbs, PRICES and VERSIONS
 *   cs/src/Scrapyard.Meta/UnlockTables.cs   every lock on a chassis, a level and a card
 *   cs/src/Scrapyard.Meta/Achievements.cs   the achievement table, platform keys included
 *
 * WHY GENERATE RATHER THAN PORT. `Scrapyard.Core` knows a card by an integer and a workshop upgrade
 * by its effects: names, blurbs, costs and versions change nothing about what happens, so none of
 * them is in the ported simulation. But the front-end has to draw them and the shop has to charge
 * them, and retyping thirty-seven strings and sixteen prices into another language is how three
 * cards end up wearing each other's names and one upgrade is quietly half price.
 *
 * THE ORDER IS THE FORMAT in both tables: index i is catalog index i. Re-run after adding,
 * renaming or REORDERING anything in either catalog. Both emitted classes carry a `Verify` that
 * refuses to start when the length no longer matches the ported catalog.
 *
 * `version` is load-bearing rather than decorative: it is what a save compares a purchase against,
 * and a mismatch REFUNDS the purchase rather than silently re-pricing it. Bump it in the TypeScript
 * whenever a workshop upgrade's effect changes, and regenerate.
 */

