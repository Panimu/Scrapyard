/// <summary>
/// A 5x7 bitmap font with descenders, drawn from a table in this file.
/// </summary>
/// <remarks>
/// <para>
/// AUTHORED HERE RATHER THAN LOADED, and the reason is worth stating because "just add a font" is
/// the obvious move. A TTF in the repository is a licence obligation and a permanent asset, which
/// this project requires approval for every time; a system font (Segoe, Arial) is not on a Steam
/// Deck; and the house art generator draws through headless Chromium, which is not installed on
/// every machine that has to build this. A table in a source file has none of those problems and
/// cannot go missing at runtime.
/// </para>
/// <para>
/// It also happens to be the right typeface for the game. The sprites are pixel art at 26 to 112
/// units; a hinted vector face rendered beside them reads as a debug overlay rather than as part of
/// the picture.
/// </para>
/// <para>
/// ONE BYTE PER ROW, low bit leftmost, eight rows per glyph. Rows 0-6 are the body with the
/// baseline under row 6; row 7 is the descender row, which only <c>g j p q y</c>, the comma and the
