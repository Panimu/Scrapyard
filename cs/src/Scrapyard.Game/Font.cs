    /// <summary>Width in pixels of a string at the given scale, tracking included.</summary>
    /// <inheritdoc cref="FontMetrics.Measure"/>
    public static int Measure(string s, int scale) => FontMetrics.Measure(s, scale);

    /// <summary>
    /// Draws a string with its top-left at (x, y). <paramref name="pixel"/> is any 1x1 white
    /// texture; every lit cell is one quad, which is fine for the handful of short strings a HUD
    /// puts on screen.
    /// </summary>
    public static void Draw(SpriteBatch batch, Texture2D pixel, string s, int x, int y, int scale,
                            Color colour)
    {
        int penX = x;
        foreach (char ch in s)
        {
            if (ch == '\n')
            {
                penX = x;
                y += LineHeight * scale;
                continue;
            }

            int c = ch;
            if (c >= First && c <= Last)
            {
                int at = (c - First) * GlyphH;
                for (int row = 0; row < GlyphH; row++)
                {
                    int bits = Bits[at + row];
                    if (bits == 0) continue;
                    for (int col = 0; col < GlyphW; col++)
                    {
                        if ((bits & (1 << col)) == 0) continue;
                        batch.Draw(pixel,
                            new Rectangle(penX + col * scale, y + row * scale, scale, scale),
                            colour);
                    }
                }
            }

            penX += (GlyphW + Tracking) * scale;
        }
    }

    /// <summary>Draws a string centred on <paramref name="cx"/>.</summary>
    public static void DrawCentred(SpriteBatch batch, Texture2D pixel, string s, int cx, int y,
                                   int scale, Color colour) =>
        Draw(batch, pixel, s, cx - Measure(s, scale) / 2, y, scale, colour);

    /// <summary>
    /// Draws a string centred on <paramref name="centre"/> and spun about it.
    /// </summary>
    /// <remarks>
    /// EVERY LIT PIXEL IS ITS OWN ROTATED QUAD, not the finished word rotated as one block. This
    /// font has no texture backing it - <see cref="Draw"/> blits a scaled quad per lit cell - so
    /// there is no single sprite to hand MonoGame's rotated <c>Draw</c> overload. Rotating each
    /// cell's OFFSET from centre and its OWN quad by the same angle gives the same picture a
    /// pre-rendered rotated sprite would.
    /// </remarks>
    public static void DrawCentredRotated(SpriteBatch batch, Texture2D pixel, string s,
                                          Vector2 centre, int scale, Color colour, float rotation)
    {
        float cos = (float)System.Math.Cos(rotation);
        float sin = (float)System.Math.Sin(rotation);

        // Local space, unrotated: (0, 0) is the centre of the string's bounding box.
        float penX = -Measure(s, scale) / 2f;
        float top = -(GlyphH * scale) / 2f;

        foreach (char ch in s)
        {
            int c = ch;
            if (c >= First && c <= Last)
            {
                int at = (c - First) * GlyphH;
                for (int row = 0; row < GlyphH; row++)
                {
                    int bits = Bits[at + row];
                    if (bits == 0) continue;
                    for (int col = 0; col < GlyphW; col++)
                    {
                        if ((bits & (1 << col)) == 0) continue;
                        float lx = penX + col * scale;
                        float ly = top + row * scale;
                        var pos = new Vector2(
                            centre.X + lx * cos - ly * sin,
                            centre.Y + lx * sin + ly * cos);
                        batch.Draw(pixel, pos, null, colour, rotation, Vector2.Zero,
                                   new Vector2(scale, scale), SpriteEffects.None, 0f);
                    }
                }
            }
            penX += (GlyphW + Tracking) * scale;
        }
    }

    /// <summary>
    /// Greedy word wrap to a pixel width. Returns the lines; the caller decides line spacing.
    /// </summary>
    /// <remarks>
    /// A word longer than the whole width is left to overflow rather than being broken mid-word:
    /// this font's users are card names and one-line descriptions, and a hyphenated "amm-unition"
    /// would be worse than a line that runs a little wide.
    /// </remarks>
    public static List<string> Wrap(string s, int widthPx, int scale)
    {
        var lines = new List<string>();
        var line = new System.Text.StringBuilder();
        foreach (string word in s.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            string candidate = line.Length == 0 ? word : line + " " + word;
            if (line.Length > 0 && Measure(candidate, scale) > widthPx)
            {
                lines.Add(line.ToString());
                line.Clear();
                line.Append(word);
            }
            else
            {
                line.Clear();
                line.Append(candidate);
            }
        }
        if (line.Length > 0) lines.Add(line.ToString());
        return lines;
    }
